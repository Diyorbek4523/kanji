export function t(key, ...args) {
  let s = (D[lang] && D[lang][key]) ?? D.uz[key] ?? key;
  args.forEach((a, i) => { s = s.split(`{${i}}`).join(String(a)); });
  return s;
}

// ---- Kontentni (ma'no, tarjima, grammatika) joriy tilga o'tkazish ----
const BASE = {
  kanji: Object.fromEntries(KANJI.map(k => [k.id, [k.m, k.mn, k.ex.m]])),
  vocab: Object.fromEntries(VOCAB.map(v => [v.id, v.uz])),
  sent: Object.fromEntries(SENTENCES.map(s => [s.id, s.uz])),
  gram: Object.fromEntries(Object.values(GRAMMAR).flat().map(g => [g.id, [g.p, g.uz]])),
};
function applyContent() {
  const C = lang === "en" ? CONTENT_EN : lang === "ru" ? CONTENT_RU : null;
  KANJI.forEach(k => { const b = BASE.kanji[k.id], x = C && C.kanji[k.id]; k.m = x ? x[0] : b[0]; k.mn = x ? x[1] : b[1]; k.ex.m = x ? x[2] : b[2]; });
  VOCAB.forEach(v => { v.uz = (C && C.vocab[v.id]) || BASE.vocab[v.id]; });
  SENTENCES.forEach(s => { s.uz = (C && C.sent[s.id]) || BASE.sent[s.id]; });
  Object.values(GRAMMAR).flat().forEach(g => { const b = BASE.gram[g.id], x = C && C.gram[g.id]; g.p = x ? x[0] : b[0]; g.uz = x ? x[1] : b[1]; });
  document.documentElement.lang = lang;
}
export function setLang(l) {
  if (!LANGS.includes(l)) return;
  lang = l;
  try { localStorage.setItem("lang", l); } catch (e) {}
  applyContent();
}
